export function parseSheet(sheet: Sheet): number[][] {
    return sheet.map((row) => [...row].map((cell) => (cell === '.' ? 0 : Number(cell))));
}

export function shiftSheet(sheet: Sheet, dx: number): Sheet {
    return sheet.map((row, y) => {
        if (y < 2) {
            return row;
        }
        const cells = [...row];
        if (dx > 0) {
            cells.unshift(cells.pop() ?? '.');
        } else if (dx < 0) {
            cells.push(cells.shift() ?? '.');
        }
        return cells.join('');
    });
}

export function attackSheet(sheet: Sheet): Sheet {
    return sheet.map((row, y) => {
        if (y === 4 || y === 5) {
            return `${row.slice(1)}4`;
        }
        return row;
    });
}

export function champSheet(id: string): Sheet {
    return CHAMP_SHEETS[id] ?? CHAMP_SHEETS.david;
}

