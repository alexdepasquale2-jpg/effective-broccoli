export function unlockedCodex({ braidsTotal = 0, songsCleared = {} } = {}) {
  return CODEX.filter((e) =>
    e.unlock.song ? Boolean(songsCleared[e.unlock.song]) : braidsTotal >= e.unlock.braids,
  );
}

export function nextCodexUnlock({ braidsTotal = 0, songsCleared = {} } = {}) {
  return (
    CODEX.find(
      (e) =>
        !(e.unlock.song ? Boolean(songsCleared[e.unlock.song]) : braidsTotal >= e.unlock.braids),
    ) ?? null
  );
}
